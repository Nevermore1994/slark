#!/usr/bin/env python3
"""
gen_player_state.py - cross-language SSOT code generator for PlayerState/PlayerEvent/Error

Parses PlayerState/PlayerEvent from C++ PlayerTypes.h and Error from internal/Error.h,
generating:
  1. Kotlin: SlarkPlayerState.kt / SlarkPlayerEvent.kt / SlarkPlayerErrorCode.kt
  2. C++ JNI: PlayerStateNames.h
  3. iOS: NS_ENUM definitions in SlarkPlayer.h (written in place)

Usage:
  python3 scripts/gen_player_state.py [--check] [--cpp-header PATH] [--error-header PATH]
                                       [--kotlin-dir DIR] [--jni-dir DIR] [--ios-header PATH]

  --check         only verify generated files match the existing ones (for CI)
  --cpp-header    C++ PlayerTypes.h path (default auto-detect)
  --error-header  internal/Error.h path (default auto-detect)
  --kotlin-dir    Kotlin output directory (default auto-detect)
  --jni-dir       JNI header output directory (default auto-detect)
  --ios-header    iOS SlarkPlayer.h path (default auto-detect)
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

# ---------------------------------------------------------------------------
# 项目路径自动发现
# ---------------------------------------------------------------------------
SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR.parent

DEFAULT_CPP_HEADER = PROJECT_ROOT / "include" / "PlayerTypes.h"
DEFAULT_ERROR_HEADER = PROJECT_ROOT / "internal" / "Error.h"
DEFAULT_KOTLIN_DIR = (
    PROJECT_ROOT
    / "src"
    / "platform"
    / "Android"
    / "sdk"
    / "src"
    / "main"
    / "java"
    / "com"
    / "slark"
    / "api"
)
DEFAULT_JNI_DIR = (
    PROJECT_ROOT
    / "src"
    / "platform"
    / "Android"
    / "sdk"
    / "src"
    / "main"
    / "cpp"
    / "jni"
)
DEFAULT_IOS_HEADER = (
    PROJECT_ROOT / "src" / "platform" / "iOS" / "interface" / "SlarkPlayer.h"
)

# ---------------------------------------------------------------------------
# 数据模型
# ---------------------------------------------------------------------------

@dataclass
class EnumDef:
    name: str
    underlying_type: str = ""
    values: list[str] = field(default_factory=list)
    explicit_values: dict[str, int] = field(default_factory=dict)


# ---------------------------------------------------------------------------
# C++ PlayerTypes.h 解析
# ---------------------------------------------------------------------------

ENUM_PATTERN = re.compile(
    r"enum\s+class\s+(\w+)\s*(?::\s*(\w+))?\s*\{([^}]*)\}", re.MULTILINE
)


def parse_cpp_enums(header_path: Path) -> dict[str, EnumDef]:
    """Parse all enum class definitions from a C++ header file."""
    text = header_path.read_text(encoding="utf-8")
    result: dict[str, EnumDef] = {}

    for m in ENUM_PATTERN.finditer(text):
        enum_name = m.group(1)
        underlying = m.group(2) or ""
        body = m.group(3)

        values: list[str] = []
        explicit_values: dict[str, int] = {}

        for entry in body.split(","):
            entry = entry.strip()
            if not entry:
                continue
            # Handle explicit value assignment like "FileError = 1000"
            if "=" in entry:
                name, val_str = entry.split("=", 1)
                name = name.strip()
                val_str = val_str.strip()
                values.append(name)
                try:
                    explicit_values[name] = int(val_str)
                except ValueError:
                    pass
            else:
                # Remove trailing comments
                name = entry.split("//")[0].strip()
                if name:
                    values.append(name)

        result[enum_name] = EnumDef(
            name=enum_name,
            underlying_type=underlying,
            values=values,
            explicit_values=explicit_values,
        )

    return result


# ---------------------------------------------------------------------------
# Kotlin 生成
# ---------------------------------------------------------------------------

KOTLIN_FILE_HEADER = """\
//
// Copyright (c) 2022-2026 Nevermore1994. All rights reserved.
//
// This file is part of Slark.
// Licensed under the MIT License.
//
// ⚠️ AUTO-GENERATED by scripts/gen_player_state.py — DO NOT EDIT MANUALLY
//

package com.slark.api
"""

KOTLIN_ENUM_TEMPLATE = """\
{header}
enum class {class_name} {{
{values}
}}
"""


def generate_kotlin_enum(enum_def: EnumDef, class_name: str) -> str:
    """Generate Kotlin enum class source."""
    # Compute actual C++ enum values (auto-increment from last explicit value)
    actual_values: list[int] = []
    current = 0
    for v in enum_def.values:
        if v in enum_def.explicit_values:
            current = enum_def.explicit_values[v]
        actual_values.append(current)
        current += 1

    needs_value_param = any(v != i for i, v in enumerate(actual_values))

    value_lines: list[str] = []
    for i, v in enumerate(enum_def.values):
        if needs_value_param:
            value_lines.append(f"    {v}({actual_values[i]})")
        else:
            value_lines.append(f"    {v}")

    values_str = ",\n".join(value_lines)
    class_decl = f"{class_name}(val value: Int)" if needs_value_param else class_name

    return KOTLIN_ENUM_TEMPLATE.format(
        header=KOTLIN_FILE_HEADER,
        class_name=class_decl,
        values=values_str,
    )


# ---------------------------------------------------------------------------
# C++ PlayerStateNames.h 生成
# ---------------------------------------------------------------------------

CPP_HEADER_TEMPLATE = """\
//
// Copyright (c) 2026 Nevermore-. All rights reserved.
//
// ⚠️ AUTO-GENERATED by scripts/gen_player_state.py — DO NOT EDIT MANUALLY
//

#pragma once

#include "PlayerTypes.h"

#include <cstddef>

namespace slark {{

{enum_name_arrays}
}} // namespace slark
"""

CPP_ENUM_ARRAY_TEMPLATE = """\
// {enum_name} enum name mapping, one-to-one with the C++ and Kotlin enums
inline constexpr const char* k{enum_name}Names[] = {{
{values}
}};

constexpr size_t k{enum_name}Count = std::size(k{enum_name}Names);

// Compile-time check: the name array length must match the enum value count
static_assert(k{enum_name}Count == static_cast<size_t>({enum_name}::{last_value}) + 1,
              "k{enum_name}Names size must match {enum_name} enum count");
"""


def generate_cpp_names_header(enums: dict[str, EnumDef]) -> str:
    """Generate PlayerStateNames.h with name arrays for all parsed enums."""
    # Only generate arrays for enums that are sequential (no explicit values)
    # or have sequential implicit values
    array_blocks: list[str] = []

    for enum_name, enum_def in enums.items():
        # Skip enums with non-sequential explicit values (like PlayerErrorCode)
        if enum_def.explicit_values:
            has_non_sequential = any(
                v != i for i, v in enumerate(
                    enum_def.explicit_values.get(ev, i)
                    for i, ev in enumerate(enum_def.values)
                )
            )
            if has_non_sequential:
                continue

        value_lines = []
        for i, v in enumerate(enum_def.values):
            comma = "," if i < len(enum_def.values) - 1 else ""
            value_lines.append(f'    "{v}"{comma}    // {i}')

        values_str = "\n".join(value_lines)
        last_value = enum_def.values[-1] if enum_def.values else "Unknown"

        block = CPP_ENUM_ARRAY_TEMPLATE.format(
            enum_name=enum_name,
            values=values_str,
            last_value=last_value,
        )
        array_blocks.append(block)

    return CPP_HEADER_TEMPLATE.format(
        enum_name_arrays="\n".join(array_blocks),
    )


# ---------------------------------------------------------------------------
# iOS NS_ENUM 生成
# ---------------------------------------------------------------------------

# 注释行在 Error.h body 中的正则：匹配 "// General errors(0 - 99)" 这类行
ERROR_COMMENT_PATTERN = re.compile(r"^\s*//.*$")


def generate_ios_enum(enum_def: EnumDef, ios_class_name: str | None = None) -> str:
    """Generate iOS NS_ENUM definition."""
    value_lines: list[str] = []
    # ios_class_name 优先，否则用 Slark{enum_name}
    type_name = ios_class_name if ios_class_name else f"Slark{enum_def.name}"
    prefix = type_name  # 枚举值前缀与类型名一致

    for v in enum_def.values:
        if v in enum_def.explicit_values:
            value_lines.append(f"    {prefix}{v} = {enum_def.explicit_values[v]}")
        else:
            value_lines.append(f"    {prefix}{v}")

    values_str = ",\n".join(value_lines)
    return f"typedef NS_ENUM(NSUInteger, {type_name}) {{\n{values_str}\n}};"


def generate_ios_error_enum(enum_def: EnumDef, header_text: str) -> str:
    """Generate SlarkPlayerErrorCode NS_ENUM with group comments from Error.h."""
    type_name = "SlarkPlayerErrorCode"
    prefix = type_name

    # 从 Error.h 原文中提取注释行与枚举值的顺序关系
    body_match = re.search(r"enum\s+class\s+Error[^{]*\{([^}]*)\}", header_text, re.MULTILINE)
    if not body_match:
        return generate_ios_enum(enum_def, type_name)

    body = body_match.group(1)
    value_lines: list[str] = []
    current_val = 0
    value_index = 0

    for raw_line in body.splitlines():
        stripped = raw_line.strip()
        if not stripped:
            continue
        # 注释行直接保留
        if stripped.startswith("//"):
            value_lines.append(f"    {stripped}")
            continue
        # 枚举值行
        entry = stripped.rstrip(",")
        if "=" in entry:
            name, val_str = entry.split("=", 1)
            name = name.strip()
            try:
                current_val = int(val_str.strip())
            except ValueError:
                pass
        else:
            name = entry.split("//")[0].strip()
        if not name:
            continue
        comma = "," if value_index < len(enum_def.values) - 1 else ""
        value_lines.append(f"    {prefix}{name} = {current_val}{comma}")
        current_val += 1
        value_index += 1

    values_str = "\n".join(value_lines)
    return f"typedef NS_ENUM(NSUInteger, {type_name}) {{\n{values_str}\n}};"


# 用于在 SlarkPlayer.h 中定位并替换 SlarkPlayerErrorCode NS_ENUM 块
IOS_ERROR_ENUM_PATTERN = re.compile(
    r"typedef NS_ENUM\(NSUInteger, SlarkPlayerErrorCode\)\s*\{[^}]*\};",
    re.MULTILINE,
)


def update_ios_header(ios_path: Path, new_enum_block: str) -> bool:
    """Replace SlarkPlayerErrorCode NS_ENUM block in SlarkPlayer.h. Returns True if changed."""
    text = ios_path.read_text(encoding="utf-8")
    new_text, count = IOS_ERROR_ENUM_PATTERN.subn(new_enum_block, text)
    if count == 0:
        print(f"  Warning: SlarkPlayerErrorCode NS_ENUM not found in {ios_path}", file=sys.stderr)
        return False
    if new_text == text:
        return False
    ios_path.write_text(new_text, encoding="utf-8")
    return True

# ---------------------------------------------------------------------------
# Kotlin 文件名映射
# ---------------------------------------------------------------------------

KOTLIN_CLASS_MAP = {
    "PlayerState": "SlarkPlayerState",
    "PlayerEvent": "SlarkPlayerEvent",
}

# Error.h 中的枚举 → Kotlin 类名映射
ERROR_KOTLIN_CLASS_MAP = {
    "Error": "SlarkPlayerErrorCode",
}


# ---------------------------------------------------------------------------
# 主流程
# ---------------------------------------------------------------------------

def write_if_changed(content: str, path: Path) -> bool:
    """Write content to file only if it differs from existing. Returns True if written."""
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def check_consistency(content: str, path: Path) -> bool:
    """Check if generated content matches existing file. Returns True if consistent."""
    if not path.exists():
        print(f"  ✗ {path} does not exist", file=sys.stderr)
        return False
    existing = path.read_text(encoding="utf-8")
    if existing != content:
        print(f"  ✗ {path} is out of sync with C++ definition", file=sys.stderr)
        return False
    print(f"  ✓ {path} is up to date")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate cross-language enum definitions from C++ PlayerTypes.h"
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Only check if generated files are in sync (for CI)",
    )
    parser.add_argument(
        "--cpp-header",
        type=Path,
        default=DEFAULT_CPP_HEADER,
        help="Path to C++ PlayerTypes.h",
    )
    parser.add_argument(
        "--kotlin-dir",
        type=Path,
        default=DEFAULT_KOTLIN_DIR,
        help="Output directory for Kotlin enum files",
    )
    parser.add_argument(
        "--jni-dir",
        type=Path,
        default=DEFAULT_JNI_DIR,
        help="Output directory for JNI C++ headers",
    )
    parser.add_argument(
        "--error-header",
        type=Path,
        default=DEFAULT_ERROR_HEADER,
        help="Path to internal/Error.h (SSOT for error codes)",
    )
    parser.add_argument(
        "--ios-header",
        type=Path,
        default=DEFAULT_IOS_HEADER,
        help="Path to iOS SlarkPlayer.h",
    )
    args = parser.parse_args()

    # Parse C++ header
    if not args.cpp_header.exists():
        print(f"Error: C++ header not found: {args.cpp_header}", file=sys.stderr)
        return 1

    enums = parse_cpp_enums(args.cpp_header)
    if not enums:
        print("Error: No enum class definitions found in header", file=sys.stderr)
        return 1

    print(f"Parsed enums from {args.cpp_header}: {', '.join(enums.keys())}")

    # Parse Error.h as SSOT for error codes
    error_enums: dict[str, EnumDef] = {}
    if args.error_header.exists():
        error_enums = parse_cpp_enums(args.error_header)
        print(f"Parsed enums from {args.error_header}: {', '.join(error_enums.keys())}")
    else:
        print(f"Warning: Error header not found: {args.error_header}", file=sys.stderr)

    all_ok = True

    # Generate Kotlin files from PlayerTypes.h enums (PlayerState, PlayerEvent)
    for enum_name, enum_def in enums.items():
        kotlin_class = KOTLIN_CLASS_MAP.get(enum_name)
        if not kotlin_class:
            continue

        kotlin_content = generate_kotlin_enum(enum_def, kotlin_class)
        kotlin_path = args.kotlin_dir / f"{kotlin_class}.kt"

        if args.check:
            if not check_consistency(kotlin_content, kotlin_path):
                all_ok = False
        else:
            written = write_if_changed(kotlin_content, kotlin_path)
            status = "written" if written else "unchanged"
            print(f"  {kotlin_path}: {status}")

    # Generate Kotlin files from Error.h enums (SlarkPlayerErrorCode)
    for enum_name, enum_def in error_enums.items():
        kotlin_class = ERROR_KOTLIN_CLASS_MAP.get(enum_name)
        if not kotlin_class:
            continue

        kotlin_content = generate_kotlin_enum(enum_def, kotlin_class)
        kotlin_path = args.kotlin_dir / f"{kotlin_class}.kt"

        if args.check:
            if not check_consistency(kotlin_content, kotlin_path):
                all_ok = False
        else:
            written = write_if_changed(kotlin_content, kotlin_path)
            status = "written" if written else "unchanged"
            print(f"  {kotlin_path}: {status}")

    # Generate PlayerStateNames.h
    cpp_content = generate_cpp_names_header(enums)
    cpp_path = args.jni_dir / "PlayerStateNames.h"

    if args.check:
        if not check_consistency(cpp_content, cpp_path):
            all_ok = False
    else:
        written = write_if_changed(cpp_content, cpp_path)
        status = "written" if written else "unchanged"
        print(f"  {cpp_path}: {status}")

    # Generate iOS SlarkPlayerErrorCode directly into SlarkPlayer.h
    error_enum_def = error_enums.get("Error")
    if error_enum_def and args.ios_header.exists():
        error_header_text = args.error_header.read_text(encoding="utf-8")
        ios_enum_block = generate_ios_error_enum(error_enum_def, error_header_text)
        if args.check:
            existing = args.ios_header.read_text(encoding="utf-8")
            if IOS_ERROR_ENUM_PATTERN.search(existing) and \
               IOS_ERROR_ENUM_PATTERN.sub(ios_enum_block, existing) == existing:
                print(f"  ✓ {args.ios_header} SlarkPlayerErrorCode is up to date")
            else:
                print(f"  ✗ {args.ios_header} SlarkPlayerErrorCode is out of sync", file=sys.stderr)
                all_ok = False
        else:
            changed = update_ios_header(args.ios_header, ios_enum_block)
            status = "written" if changed else "unchanged"
            print(f"  {args.ios_header}: {status}")
    elif not args.ios_header.exists():
        print(f"  Warning: iOS header not found: {args.ios_header}", file=sys.stderr)

    if args.check:
        if all_ok:
            print("\n✓ All generated files are in sync")
            return 0
        else:
            print("\n✗ Some files are out of sync. Run: python3 scripts/gen_player_state.py",
                  file=sys.stderr)
            return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
